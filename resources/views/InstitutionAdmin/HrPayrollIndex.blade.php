<script>
    (function () {
        var monthEl = document.getElementById('payrollMonthPicker');
        var startEl = document.getElementById('payrollPeriodStart');
        var endEl = document.getElementById('payrollPeriodEnd');
        if (!monthEl || !startEl || !endEl) return;

        function setFromMonth(ym) {
            if (!/^\d{4}-\d{2}$/.test(ym)) return;
            var parts = ym.split('-');
            var y = parseInt(parts[0], 10);
            var m = parseInt(parts[1], 10);
            var lastDay = new Date(y, m, 0).getDate();
            var mm = String(m).padStart(2, '0');
            var dd = String(lastDay).padStart(2, '0');
            startEl.value = y + '-' + mm + '-01';
            endEl.value = y + '-' + mm + '-' + dd;
        }

        monthEl.addEventListener('change', function () {
            setFromMonth(this.value);
        });

        startEl.addEventListener('change', function () {
            if (this.value && this.value.length >= 7) {
                var ym = this.value.slice(0, 7);
                monthEl.value = ym;
                setFromMonth(ym);
            }
        });

        endEl.addEventListener('change', function () {
            if (this.value && this.value.length >= 7) {
                var ym = this.value.slice(0, 7);
                monthEl.value = ym;
                setFromMonth(ym);
            }
        });
    })();
</script>
